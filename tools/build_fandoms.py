#!/usr/bin/env python3
"""Build the embedded fandom index for the AO3 browser.

Input: one HTML page per media category, saved from
    https://archiveofourown.org/media
and each category's
    https://archiveofourown.org/media/<category>/fandoms
Those pages are large (Books & Literature alone is ~3.2 MB; the full set was
~30 MB), so they are only downloaded when refreshing this snapshot, never at
runtime on the device.

Output, under ao3.koplugin/data/fandoms/:
    index.lua            categories, fandom counts, letters present
    <n>/<L>.tsv.z        one zlib-deflated file per category per letter

Each letter file is a 4-byte little-endian uncompressed length followed by a
zlib stream (what KOReader's ffi/zlib.zlib_uncompress expects). The plugin
reads index.lua plus the single letter file the user opens, so memory stays
flat regardless of how many fandoms the archive has.

Usage:
    python3 tools/build_fandoms.py <pages_dir> <output_dir> [--include-uncategorized]
"""

import io
import os
import re
import struct
import sys
import zlib

SKIP_BY_DEFAULT = {"uncategorized fandoms"}


def decode(text):
    return (
        text.replace("&amp;", "&")
        .replace("&#39;", "'")
        .replace("&quot;", '"')
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("\t", " ")
        .strip()
    )


def write_letter(path, rows):
    text = "".join("%s\t%s\t%s\n" % row for row in rows)
    data = zlib.compress(text.encode("utf-8"), 9)
    with open(path, "wb") as handle:
        handle.write(struct.pack("<I", len(text.encode("utf-8"))))
        handle.write(data)


def main(pages_dir, out_dir, include_uncategorized):
    media_path = os.path.join(pages_dir, "00_media.html")
    media = io.open(media_path, encoding="utf-8", errors="replace").read()
    categories = [
        decode(m.group(1))
        for m in re.finditer(
            r'<li id="medium_\d+"[^>]*>\s*<h3 class="heading"><a href="[^"]+">([^<]+)</a>',
            media,
            re.S,
        )
    ]
    if not categories:
        sys.exit("no media categories found in %s" % media_path)

    os.makedirs(out_dir, exist_ok=True)
    index = []
    total = 0

    for number, category in enumerate(categories, start=1):
        if not include_uncategorized and category.casefold() in SKIP_BY_DEFAULT:
            print("%-42s skipped" % category)
            continue

        page = os.path.join(pages_dir, "%02d.html" % number)
        html = io.open(page, encoding="utf-8", errors="replace").read()

        entries = {}
        # Counts are present on category pages and absent on the
        # "Uncategorized Fandoms" page.
        for match in re.finditer(
            r'<a class="tag" href="(/tags/[^"]+/works)">([^<]+)</a>(?:\s*\((\d+)\))?',
            html,
        ):
            url, name, count = decode(match.group(1)), decode(match.group(2)), match.group(3) or ""
            if name:
                entries[url] = (name, url, count)

        rows = sorted(entries.values(), key=lambda row: (row[0].casefold(), row[0]))
        buckets = {}
        for name, url, count in rows:
            first = name[0]
            letter = first.upper() if first.isascii() and first.isalpha() else "#"
            buckets.setdefault(letter, []).append((name, url, count))

        category_dir = os.path.join(out_dir, str(number))
        os.makedirs(category_dir, exist_ok=True)
        letters = sorted(buckets.keys(), key=lambda letter: (letter == "#", letter))
        for letter in letters:
            write_letter(os.path.join(category_dir, letter + ".tsv.z"), buckets[letter])

        index.append((number, category, len(rows), letters))
        total += len(rows)
        print("%-42s %6d fandoms" % (category, len(rows)))

    with io.open(
        os.path.join(out_dir, "index.lua"), "w", encoding="utf-8", newline="\n"
    ) as handle:
        handle.write("-- Generated by tools/build_fandoms.py; do not edit by hand.\n")
        handle.write("return {\n")
        for number, category, count, letters in index:
            handle.write(
                '    { index = %d, name = "%s", count = %d, letters = { %s } },\n'
                % (
                    number,
                    category.replace('"', '\\"'),
                    count,
                    ", ".join('"%s"' % letter for letter in letters),
                )
            )
        handle.write("}\n")

    print("total fandoms: %d" % total)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    pages = args[0] if args else "fandom_pages"
    out = args[1] if len(args) > 1 else os.path.join("ao3.koplugin", "data", "fandoms")
    main(pages, out, "--include-uncategorized" in sys.argv)
